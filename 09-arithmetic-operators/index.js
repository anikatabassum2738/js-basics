// operators - arithmetic, assignment, comparison, logical, bitwise
// we use this operators with our variables and constants to create expressions and can implement logics and algorithms

// arithmetic operators

let x = 10;
let y = 3;

console.log(x + y); //plus
console.log(x - y); //minus
console.log(x * y); //multiply
console.log(x / y); //divide
console.log(x % y); //reminder
console.log(x ** y); //power

// Increment (++)
console.log(++x);

console.log(x++); //show the value first and then will increment
console.log(x);

// Decrement (--)
console.log(--x);

