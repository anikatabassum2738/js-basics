// operators - arithmetic, assignment, comparison, logical, bitwise
// we use this operators with our variables and constants to create expressions and can implement logics and algorithms

// comparison operators

let x = 1;

// Relational
console.log(x > 0); //greater than
console.log(x >= 0); //greater than equal
console.log(x < 0); //less than
console.log(x <= 0); //less than equal

// Equality
console.log(x === 1); //equal
console.log(x !== 1); //not equal