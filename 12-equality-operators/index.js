// equality operators

// Strict Equality (same Type + Same Value)
console.log(1 === 1);
console.log('1' === 1);


// Lose Equality - (value) it will match what we have on the right side to what we have on the left side
console.log(1 == 1);
console.log('1' == 1);
console.log(true == 1);