// operators - arithmetic, assignment, comparison, logical, bitwise
// we use this operators with our variables and constants to create expressions and can implement logics and algorithms

// operator precedence - higher precedence operators are evaluated before lower precedence operators

let x = 2 + 3 * 4; // here * has higher precedence than +, so it will be evaluated first
console.log(x); // 14

let y = (2 + 3) * 4; // here we are using parentheses to change the precedence, so + will be evaluated first
console.log(y); // 20