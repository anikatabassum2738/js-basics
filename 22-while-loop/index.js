// loops - they repeat an action a number of times
// Loops - for loop, while loop, do while loop, for in loop, for of loop

// While loop

// while (condition) {
//     statement
// }


for (let i = 1; i <= 5; i++) {
    if (i % 2 !== 0) console.log(i);
}

let i = 0;
while (i < 5) {
    if (i % 2 !== 0) console.log(i);
    i++;
}